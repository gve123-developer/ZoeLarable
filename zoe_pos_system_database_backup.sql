CREATE VIEW public.view_daily_sales_profit AS
 SELECT (t.transaction_date)::date AS sale_date,
    count(t.id) AS total_transactions,
    sum(t.total_amount) AS gross_revenue,
    sum(((ti.quantity)::numeric * ti.cost_at_sale)) AS total_cost,
    (sum(t.total_amount) - sum(((ti.quantity)::numeric * ti.cost_at_sale))) AS gross_profit
   FROM (public.transactions t
     JOIN public.transaction_items ti ON ((t.id = ti.transaction_id)))
  GROUP BY ((t.transaction_date)::date);


