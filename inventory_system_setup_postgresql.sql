BEGIN;

DROP VIEW IF EXISTS view_daily_sales_profit;
DROP VIEW IF EXISTS view_product_performance;
DROP VIEW IF EXISTS view_stock_status;

DROP TABLE IF EXISTS transaction_items CASCADE;
DROP TABLE IF EXISTS inventory_loss CASCADE;
DROP TABLE IF EXISTS transactions CASCADE;
DROP TABLE IF EXISTS user_activity_logs CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS password_resets CASCADE;
DROP TABLE IF EXISTS audit_logs CASCADE;
DROP TABLE IF EXISTS deleted_products CASCADE;
DROP TABLE IF EXISTS error_logs CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS users CASCADE;


-- 1. Users
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    last_login_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 2. Password Resets
CREATE TABLE password_resets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL,
    token VARCHAR(6) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_email ON password_resets(email);


-- 3. Categories
CREATE TABLE categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);


-- 4. Products
CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    category_id INTEGER NULL,
    description TEXT,
    quantity INTEGER NOT NULL DEFAULT 0,
    price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    cost NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    reorder_level INTEGER NOT NULL DEFAULT 10,
    expiry_date DATE NULL,
    new_stock_quantity INTEGER NOT NULL DEFAULT 0,
    new_stock_expiry DATE NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT products_category_fk
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
        ON DELETE SET NULL
);

CREATE INDEX idx_products_category_id ON products(category_id);
CREATE INDEX idx_products_sku ON products(sku);
CREATE INDEX idx_products_name ON products(name);
CREATE INDEX idx_expiry_date ON products(expiry_date);


-- 5. Transactions
CREATE TABLE transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cashier_id INTEGER NULL,
    total_amount NUMERIC(10,2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    amount_received NUMERIC(10,2) NULL,
    change_amount NUMERIC(10,2) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'completed',
    transaction_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT transactions_cashier_fk
        FOREIGN KEY (cashier_id)
        REFERENCES users(id)
        ON DELETE SET NULL
);

CREATE INDEX idx_transactions_cashier_id ON transactions(cashier_id);
CREATE INDEX idx_transactions_date ON transactions(transaction_date);


-- 6. Transaction Items
CREATE TABLE transaction_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    price_at_sale NUMERIC(10,2) NOT NULL,
    cost_at_sale NUMERIC(10,2) NOT NULL,

    subtotal NUMERIC(10,2)
        GENERATED ALWAYS AS (quantity * price_at_sale) STORED,

    CONSTRAINT transaction_items_transaction_fk
        FOREIGN KEY (transaction_id)
        REFERENCES transactions(id)
        ON DELETE CASCADE,

    CONSTRAINT transaction_items_product_fk
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE NO ACTION
);

CREATE INDEX idx_transaction_items_transaction_id
    ON transaction_items(transaction_id);

CREATE INDEX idx_transaction_items_product_id
    ON transaction_items(product_id);


-- 7. Inventory Loss
CREATE TABLE inventory_loss (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    cost_at_loss NUMERIC(10,2) NOT NULL,
    reason VARCHAR(100),
    loss_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reported_by INTEGER NULL,

    CONSTRAINT inventory_loss_product_fk
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE,

    CONSTRAINT inventory_loss_user_fk
        FOREIGN KEY (reported_by)
        REFERENCES users(id)
        ON DELETE SET NULL
);

CREATE INDEX idx_inventory_loss_product_id
    ON inventory_loss(product_id);

CREATE INDEX idx_inventory_loss_reported_by
    ON inventory_loss(reported_by);


-- 8. Audit Logs
CREATE TABLE audit_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 9. Deleted Products
CREATE TABLE deleted_products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_id INTEGER NOT NULL,
    sku VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    description TEXT,
    quantity INTEGER DEFAULT 0,
    price NUMERIC(10,2) DEFAULT 0.00,
    cost NUMERIC(10,2) DEFAULT 0.00,
    reorder_level INTEGER DEFAULT 0,
    expiry_date DATE NULL,
    deleted_by VARCHAR(100),
    deleted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 10. Error Logs
CREATE TABLE error_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(20) NOT NULL DEFAULT 'php',
    level VARCHAR(20) NOT NULL DEFAULT 'error',
    message TEXT NOT NULL,
    file VARCHAR(500),
    line INTEGER,
    stack_trace TEXT,
    url VARCHAR(1000),
    user_name VARCHAR(100),
    extra TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_error_logs_source ON error_logs(source);
CREATE INDEX idx_error_logs_created_at ON error_logs(created_at);


-- 11. User Activity Logs
CREATE TABLE user_activity_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NULL,
    action VARCHAR(255) NOT NULL,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT user_activity_logs_user_fk
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE SET NULL
);

CREATE INDEX idx_user_activity_logs_user_id
    ON user_activity_logs(user_id);


-- =========================================================
-- VIEWS
-- =========================================================

CREATE VIEW view_daily_sales_profit AS
SELECT
    CAST(t.transaction_date AS DATE) AS sale_date,
    COUNT(t.id) AS total_transactions,
    SUM(t.total_amount) AS gross_revenue,
    SUM(ti.quantity * ti.cost_at_sale) AS total_cost,
    SUM(t.total_amount) -
        SUM(ti.quantity * ti.cost_at_sale) AS gross_profit
FROM transactions t
JOIN transaction_items ti
    ON t.id = ti.transaction_id
GROUP BY CAST(t.transaction_date AS DATE);


CREATE VIEW view_product_performance AS
SELECT
    p.id,
    p.name,
    c.name AS category_name,
    COALESCE(SUM(ti.quantity), 0) AS total_sold,
    COALESCE(SUM(ti.subtotal), 0) AS total_revenue
FROM products p
LEFT JOIN transaction_items ti
    ON p.id = ti.product_id
LEFT JOIN categories c
    ON p.category_id = c.id
GROUP BY
    p.id,
    p.name,
    c.name;


CREATE VIEW view_stock_status AS
SELECT
    products.id,
    products.sku,
    products.name,
    products.quantity,
    products.reorder_level,
    CASE
        WHEN products.quantity = 0
            THEN 'Out of Stock'
        WHEN products.quantity <= products.reorder_level
            THEN 'Low Stock'
        ELSE 'In Stock'
    END AS status
FROM products;


